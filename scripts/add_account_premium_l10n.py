def escape_kt(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def insert_entries(block: str, entries: dict[str, str]) -> str:
    existing = set(re.findall(r'"((?:\\.|[^"\\])*)"\s+to\s+', block))
    to_add = []
    for k, v in entries.items():
        if k not in existing:
            to_add.append(f'    "{escape_kt(k)}" to "{escape_kt(v)}",')
    if not to_add:
        return block
    lines = block.rstrip().split("\n")
    if lines[-1].strip() != ")":
        raise SystemExit(f"Unexpected ending: {lines[-1]!r}")
    body = lines[:-1]
    for i in range(len(body) - 1, -1, -1):
        s = body[i].rstrip()
        if s and not s.lstrip().startswith("//"):
            if not s.endswith(","):
                body[i] = s + ","
            break
    # last added entry should not require trailing comma before )
    if to_add:
        to_add[-1] = to_add[-1].rstrip(",")
    body.extend(to_add)
    body.append(")")
    return "\n".join(body)


def main() -> None:
    text = PATH.read_text(encoding="utf-8")
    m = re.search(r"internal val phraseIdentity: Map<String, String> = mapOf\((.*?)\)\n\ninternal fun phrasesFor", text, re.S)
    if not m:
        raise SystemExit("phraseIdentity not found")
    ident_full = "internal val phraseIdentity: Map<String, String> = mapOf(" + m.group(1) + ")"
    new_ident = insert_entries(ident_full, {k: k for k in NEW})
    text = text[: m.start()] + new_ident + "\n\ninternal fun phrasesFor" + text[m.end() :]

    for pack_name, lang in PACKS:
        pattern = rf"(private val {pack_name}: Map<String, String> = mapOf\()(.*?)(\n\))"
        m = re.search(pattern, text, re.S)
        if not m:
            print("WARN missing", pack_name)
            continue
        entries = {k: NEW[k][lang] for k in NEW}
        updated = insert_entries(m.group(0), entries)
        text = text[: m.start()] + updated + text[m.end() :]
        print("updated", pack_name)

    PATH.write_text(text, encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main()
